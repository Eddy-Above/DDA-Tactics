import { inArray } from 'drizzle-orm'
import { db, digimon, tamers } from '../db'
import { validateEncounterCharacterScope } from './encounterCharacterScope'

interface ContextEncounter {
  campaignId: string | null
  participants?: any[]
  pendingRequests?: any[]
  requestResponses?: any[]
}

const participantKeys = new Set(['attackerId', 'targetId', 'interceptorId', 'chosenTargetId', 'originalTargetId'])
const participantLists = new Set(['targetIds', 'originalTargetIds', 'npcTargetIds', 'tamerAreaTargetIds', 'digimonAreaTargetIds', 'gmAreaTargetIds', 'coveredTargetIds', 'allyIds'])
const participantMaps = new Set(['playerTargetInfo', 'npcAreaEligibility', 'outcomes'])
const validId = (value: unknown): value is string => typeof value === 'string' && value.length > 0 && value.length <= 200

/** Stored prompts are executable combat context, including recovery's direct character writes. */
export async function validateEncounterContextScope(encounter: ContextEncounter, additional?: unknown): Promise<void> {
  function fail(message = 'An encounter prompt refers to a character outside this campaign'): never { throw createError({ statusCode: 400, message }) }
  if (!encounter.campaignId) throw createError({ statusCode: 403, message: 'Standalone encounters are read-only' })
  const roster = encounter.participants ?? []
  if (!Array.isArray(roster)) fail('Invalid encounter participants')
  const participants = new Map(roster.map(participant => [participant.id, participant]))
  const digimonIds = new Set<string>(), tamerIds = new Set<string>(), lineIds = new Set<string>(), unknownEntities = new Set<string>()
  const participant = (value: unknown, requireRoster = true) => {
    if (!validId(value) || requireRoster && !participants.has(value)) fail('An encounter prompt refers to an unknown participant')
  }
  const collect = (target: Set<string>, value: unknown, gm = false) => {
    if (!validId(value)) fail('Invalid encounter character identifier')
    if (gm && value.toLowerCase() === 'gm') return
    target.add(value)
  }
  const entity = (value: unknown) => {
    if (!validId(value)) fail('Invalid encounter character identifier')
    const matches = roster.filter(record => record.entityId === value)
    if (!matches.length) unknownEntities.add(value)
    else for (const record of matches) collect(record.type === 'tamer' ? tamerIds : digimonIds, value)
  }
  const walk = (value: unknown, depth = 0, requireRoster = true): void => {
    if (depth > 30) fail('Encounter prompt nesting is too deep')
    if (value == null || typeof value !== 'object') return
    if (Array.isArray(value)) { for (const item of value) walk(item, depth + 1, requireRoster); return }
    const object = value as Record<string, any>
    for (const [key, item] of Object.entries(object)) {
      if (item == null) continue
      if (key === 'participantId' || key.endsWith('ParticipantId') || participantKeys.has(key)) participant(item, requireRoster)
      else if (key.endsWith('ParticipantIds') || participantLists.has(key)) {
        if (!Array.isArray(item)) fail('Invalid encounter participant identifiers')
        item.forEach((id: unknown) => participant(id, requireRoster))
      } else if (key === 'tamerId' || key.endsWith('TamerId') || key === 'ownerId' || key === 'partnerId') {
        // This is the only internal recipient generated by the area-intercede service.
        if (!(key === 'targetTamerId' && item === '__internal__' && object.type === 'intercede-group-state')) collect(tamerIds, item, true)
      } else if (key === 'digimonId' || key.endsWith('DigimonId')) collect(digimonIds, item)
      else if (key === 'digimonIds' || key.endsWith('DigimonIds')) {
        if (!Array.isArray(item)) fail('Invalid encounter Digimon identifiers')
        item.forEach((id: unknown) => collect(digimonIds, id))
      } else if (key === 'tamerIds' || key.endsWith('TamerIds')) {
        if (!Array.isArray(item)) fail('Invalid encounter Tamer identifiers')
        item.forEach((id: unknown) => collect(tamerIds, id, true))
      } else if (key === 'evolutionLineId') collect(lineIds, item)
      else if (key === 'entityId' || key.endsWith('EntityId')) entity(item)
      else if (key === 'entityIds' || key.endsWith('EntityIds')) {
        if (!Array.isArray(item)) fail('Invalid encounter entity identifiers')
        item.forEach(entity)
      } else if (participantMaps.has(key)) {
        if (typeof item !== 'object' || Array.isArray(item)) fail('Invalid encounter participant context')
        for (const [id, entry] of Object.entries(item)) {
          participant(id, requireRoster)
          if (key === 'npcAreaEligibility') {
            if (!Array.isArray(entry)) fail('Invalid encounter area eligibility')
            entry.forEach(id => participant(id, requireRoster))
          }
        }
      }
      // Unknown text, attack IDs, request IDs and arbitrary strings are not entity references.
      walk(item, depth + 1, requireRoster)
    }
  }
  for (const key of ['pendingRequests', 'requestResponses'] as const) {
    const contexts = encounter[key] ?? []
    if (!Array.isArray(contexts) || contexts.some(context => !context || typeof context !== 'object' || Array.isArray(context))) fail('Invalid encounter prompts')
    // Retained response history can outlive a removed roster slot. Its character
    // references still require campaign scope; only active prompts can execute
    // effects against participant references, which must resolve to the roster.
    walk(contexts, 0, key === 'pendingRequests')
  }
  walk(additional)
  // Generic EntityId fields can refer to either character kind, including an older
  // form not currently deployed. Resolve their real table before graph validation.
  if (unknownEntities.size) {
    const [forms, people] = await Promise.all([
      db.select({ id: digimon.id }).from(digimon).where(inArray(digimon.id, [...unknownEntities])),
      db.select({ id: tamers.id }).from(tamers).where(inArray(tamers.id, [...unknownEntities])),
    ])
    for (const form of forms) digimonIds.add(form.id)
    for (const person of people) tamerIds.add(person.id)
    if ([...unknownEntities].some(id => !forms.some(form => form.id === id) && !people.some(person => person.id === id))) fail()
  }
  await validateEncounterCharacterScope(encounter.campaignId, { digimonIds, tamerIds, evolutionLineIds: lineIds })
}
